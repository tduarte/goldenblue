#!/usr/bin/env bash
# Resolve the upstream versions of everything not managed by Fedora/Bazzite repos.
# Prints KEY=VALUE lines (versions.env). The build installs exactly these
# versions, and CI hashes this file into the image fingerprint, so a new
# upstream release triggers a rebuild while an unchanged world doesn't.
set -euo pipefail

BASE_IMAGE="${BASE_IMAGE:-ghcr.io/ublue-os/bazzite-gnome:stable}"

curl_() { curl -fsSL --retry 5 --retry-delay 3 --retry-all-errors "$@"; }

# GitHub API, authenticated when a token is available (CI) to avoid rate limits.
gh_api() {
    local auth=()
    if [[ -n "${GITHUB_TOKEN:-}" ]]; then
        auth=(-H "Authorization: Bearer ${GITHUB_TOKEN}")
    fi
    curl_ "${auth[@]}" -H "Accept: application/vnd.github+json" "https://api.github.com/$1"
}
gh_latest() { gh_api "repos/$1/releases/latest" | jq -r .tag_name; }

# Fedora release of the base (Bazzite labels its version as e.g. 44.20261006.1).
FEDORA_VERSION="$(skopeo inspect --retry-times 3 --no-tags "docker://${BASE_IMAGE}" |
    jq -r '.Labels["org.opencontainers.image.version"]' | cut -d. -f1)"

# ROCm major.minor in that Fedora (updates repo first, then GA). llama.cpp is
# rebuilt only when this or the llama.cpp tag changes.
ROCM_VERSION=""
for repo in "f${FEDORA_VERSION}-updates" "f${FEDORA_VERSION}"; do
    if v="$(curl_ "https://mdapi.fedoraproject.org/${repo}/pkg/rocm-hip" 2>/dev/null | jq -r .version)" && [[ -n "$v" && "$v" != null ]]; then
        ROCM_VERSION="$(cut -d. -f1-2 <<<"$v")"
        break
    fi
done
[[ -n "$ROCM_VERSION" ]] || {
    echo "could not resolve rocm-hip version" >&2
    exit 1
}

# llama.cpp: follow the versioned releases (vX.Y.Z), which point at a build tag,
# rather than every nightly bNNNNN.
LLAMA_RELEASE="$(gh_latest ggml-org/llama.cpp)"
LLAMA_TAG="$(curl_ "https://github.com/ggml-org/llama.cpp/releases/download/${LLAMA_RELEASE}/nightly-tag.txt" | tr -d '[:space:]')"

CLAUDE_CODE_VERSION="$(curl_ https://downloads.claude.ai/claude-code-releases/stable | tr -d '[:space:]')"
OMP_VERSION="$(gh_latest can1357/oh-my-pi)"
OPENCODE_VERSION="$(gh_latest anomalyco/opencode)"
ZED_VERSION="$(gh_latest zed-industries/zed)"
ZEN_VERSION="$(gh_latest zen-browser/desktop)"
BUN_VERSION="$(gh_latest oven-sh/bun)"
BIBATA_VERSION="$(gh_latest ful1e5/Bibata_Cursor)"
WHITESUR_TAG="$(gh_latest vinceliuice/WhiteSur-icon-theme)"
ALPHAGRID_VERSION="$(gh_latest stuarthayhurst/alphabetical-grid-extension)"

# RPM repos outside Fedora: track the repo metadata revision.
BRAVE_REPO_REV="$(curl_ https://brave-browser-rpm-release.s3.brave.com/x86_64/repodata/repomd.xml |
    sed -n 's:.*<revision>\(.*\)</revision>.*:\1:p')"
# Ghostty comes from Terra (already configured in Bazzite); its upstream tag
# stands in for the package version since Terra's repo changes constantly.
GHOSTTY_VERSION="$(gh_api 'repos/ghostty-org/ghostty/tags?per_page=20' |
    jq -r '[.[].name | select(test("^v[0-9]+\\.[0-9]+\\.[0-9]+$"))][0]')"

OUT="$(cat <<EOF
# Generated by build_files/resolve-versions.sh - do not edit
FEDORA_VERSION=${FEDORA_VERSION}
ROCM_VERSION=${ROCM_VERSION}
LLAMA_TAG=${LLAMA_TAG}
LLAMA_IMAGE_TAG=${LLAMA_TAG}-f${FEDORA_VERSION}-rocm${ROCM_VERSION}
CLAUDE_CODE_VERSION=${CLAUDE_CODE_VERSION}
OMP_VERSION=${OMP_VERSION#v}
OPENCODE_VERSION=${OPENCODE_VERSION#v}
ZED_VERSION=${ZED_VERSION#v}
ZEN_VERSION=${ZEN_VERSION}
BUN_VERSION=${BUN_VERSION#bun-v}
BIBATA_VERSION=${BIBATA_VERSION#v}
WHITESUR_TAG=${WHITESUR_TAG}
ALPHAGRID_VERSION=${ALPHAGRID_VERSION#v}
BRAVE_REPO_REV=${BRAVE_REPO_REV}
GHOSTTY_VERSION=${GHOSTTY_VERSION#v}
EOF
)"

# Fail loudly instead of building with an empty version.
if grep -E '=(null)?$' <<<"$OUT" >&2; then
    echo "error: unresolved versions above" >&2
    exit 1
fi
echo "$OUT"
